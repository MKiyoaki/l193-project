import os
import json
import argparse
import matplotlib.pyplot as plt
import matplotlib.ticker as ticker
from pathlib import Path

# Set plot style directly using matplotlib to avoid seaborn dependency
plt.style.use('seaborn-v0_8-whitegrid')
plt.rcParams["font.family"] = "serif"


def load_and_flatten_data(filepath):
    """
    Load JSON results and extract X (nodes) and Y (rates) arrays.
    Automatically handles reading the baseline score from either data["0"] or metadata.
    """
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Missing data file: {filepath}")
    
    with open(filepath, 'r', encoding='utf-8') as f:
        data_payload = json.load(f)
        raw_data = data_payload.get("data", {})
        metadata = data_payload.get("metadata", {})

    records = []
    # Faithfulness script saves baseline in metadata
    baseline_rate = metadata.get("clean_score", None) 

    for key, value in raw_data.items():
        nodes = int(key)
        rate = float(value)
        if nodes == 0:
            baseline_rate = rate
        else:
            records.append((nodes, rate))

    # Sort by number of kept nodes
    records.sort(key=lambda item: item[0])
    
    x_vals = [r[0] for r in records]
    y_vals = [r[1] for r in records]
    
    return x_vals, y_vals, baseline_rate


def main():
    """
    Main execution function for plotting the global faithfulness curve.
    """
    parser = argparse.ArgumentParser()
    parser.add_argument("--experiment_name", type=str,
                        default="nlp", choices=["nlp", "phi", "political"])
    parser.add_argument("--effects_dir", type=str, default="effects")
    args = parser.parse_args()

    # Match the filenames generated by your eval_global.py script
    sfc_file = Path(args.effects_dir) / f"global_faithfulness_sfc_{args.experiment_name}.json"
    dense_file = Path(args.effects_dir) / f"global_faithfulness_dense_{args.experiment_name}.json"

    # Fallback to current directory if not found in effects folder
    if not sfc_file.exists():
         sfc_file = Path(f"global_faithfulness_sfc_{args.experiment_name}.json")
    if not dense_file.exists():
         dense_file = Path(f"global_faithfulness_dense_{args.experiment_name}.json")

    print(f"Loading results for experiment: {args.experiment_name}")
    
    plt.figure(figsize=(10, 6))
    global_baseline = None

    # Plot SFC Data
    if sfc_file.exists():
        x_sfc, y_sfc, sfc_base = load_and_flatten_data(sfc_file)
        if x_sfc:
            plt.plot(x_sfc, y_sfc, marker='o', color='#2980b9', linewidth=2.5, 
                     markersize=6, label='SFC (SAE Features Kept)')
        if sfc_base is not None:
            global_baseline = sfc_base
    else:
        print(f"Warning: SFC data file not found at {sfc_file}")

    # Plot Dense Data
    if dense_file.exists():
        x_dense, y_dense, dense_base = load_and_flatten_data(dense_file)
        if x_dense:
            plt.plot(x_dense, y_dense, marker='s', color='#8e44ad', linewidth=2.5, 
                     markersize=6, label='Dense Neurons Kept')
        if global_baseline is None and dense_base is not None:
            global_baseline = dense_base
    else:
        print(f"Warning: Dense data file not found at {dense_file}")

    # Plot Clean Baseline
    if global_baseline is not None:
        plt.axhline(y=global_baseline, color='gray', linestyle='--', alpha=0.8, 
                    linewidth=2, label=f'Clean Model ({global_baseline:.2%})')

    # Formatting the plot
    plt.xscale('log')
    plt.xlim(8, 60000)
    
    # Automatically adjust Y-axis or set hard limits based on typical outputs
    plt.ylim(0.40, 0.90) 
    
    # Format Y-axis as percentages
    plt.gca().yaxis.set_major_formatter(ticker.PercentFormatter(xmax=1.0, decimals=0))
    
    # Add labels and title
    # Note: Faithfulness measures keeping K and ablating the rest, hence "Kept"
    plt.title(f"Global Feature Ablation Faithfulness ({args.experiment_name.upper()})", 
              fontsize=16, fontweight='bold', pad=15)
    plt.xlabel("Top K Nodes Kept (Log Scale)", fontsize=13)
    plt.ylabel("Sycophancy Rate", fontsize=13)
    
    plt.grid(True, which="both", ls="-", alpha=0.2)
    
    # Moved legend to lower right as Faithfulness curves typically trend upwards
    plt.legend(frameon=True, loc='lower right', fontsize=11)

    save_path = Path("effects") / f"faithfulness_plot_{args.experiment_name}.png"
    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches='tight')
    print(f"Plot saved successfully as '{save_path}'")


if __name__ == "__main__":
    main()